def make_state_injection_qrc(n_qubits: int, n_in: int, H_reservoir: np.ndarray,
                                tau: float = 1.0,
                                shots_per_qubit: int = 1024,
                                rng: np.random.Generator | None = None):
    """Build a QRC with state-injection input mode.

    At each timestep:
      1. Receive a 2^n_in-dim input state vector psi_in.
      2. Prepare on reservoir: |psi_in> tensor |0>^(q-n_in).
      3. Evolve full reservoir under H_reservoir for time tau.
      4. Sample M = shots_per_qubit * q shots.  Extract local Paulis
         (<Z_i>, <Z_i Z_j>), D = q(q+1)/2 features.
    NO recurrence across timesteps (input state is re-prepared each step
    -- same constraint as the classical baseline; the only memory comes
    from windowing the features later, identical for both methods).
    """
    dim = 2 ** n_qubits
    q = n_qubits
    M = shots_per_qubit * q
    U_evolve = sla.expm(-1j * H_reservoir * tau)
    if rng is None:
        rng = np.random.default_rng(0)

    idx = np.arange(dim, dtype=np.uint32)
    bits = ((idx[:, None] >> np.arange(q)[::-1]) & 1).astype(np.int8)
    signs = (1 - 2 * bits).astype(np.float64)
    iu, ju = np.triu_indices(q, k=1)
    pair_signs = signs[:, iu] * signs[:, ju]

    dim_in = 2 ** n_in
    dim_rest = 2 ** (q - n_in)
    rest_init = np.zeros(dim_rest, dtype=complex); rest_init[0] = 1.0

    def step(psi_in: np.ndarray) -> np.ndarray:
        """Inject |psi_in> on first n_in qubits, evolve, sample, return features."""
        psi_full = np.kron(psi_in, rest_init)
        psi_full = U_evolve @ psi_full
        p = np.abs(psi_full) ** 2
        s = p.sum()
        if s > 0:
            p = p / s
        counts = rng.multinomial(M, p).astype(np.float64)
        w = counts / M
        Z_vals  = w @ signs
        ZZ_vals = w @ pair_signs
        return np.concatenate([Z_vals, ZZ_vals])

    return step, q * (q + 1) // 2


