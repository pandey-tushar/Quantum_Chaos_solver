# Single-qubit Clifford rotations that map computational basis to X/Y/Z basis.
# We use the 3-basis (Pauli) shadow scheme (simplest, well-known).
# Rotation that maps measurement basis to X-eigenstates: H (Hadamard)
# To Y-eigenstates: HS^dag (or equivalently S H), depending on convention.
# To Z-eigenstates: identity.
H_GATE = (1.0 / np.sqrt(2)) * np.array([[1, 1], [1, -1]], dtype=complex)
S_DAG = np.array([[1, 0], [0, -1j]], dtype=complex)
HSDAG = H_GATE @ S_DAG  # rotates Y eigenstates to Z basis


def _rotated_probabilities(psi: np.ndarray, n: int,
                              basis_pattern: tuple[int, ...]) -> np.ndarray:
    """Probability distribution of measuring |psi> in basis given by
    basis_pattern, a length-n tuple of (0=X, 1=Y, 2=Z)."""
    BASIS_GATES = [H_GATE, HSDAG, I2]
    psi_rot = psi
    for qubit in range(n):
        b = basis_pattern[qubit]
        if b != 2:                      # Z = identity rotation
            psi_rot = _apply_single_qubit_gate(psi_rot, n, qubit, BASIS_GATES[b])
    p = np.abs(psi_rot) ** 2
    s = p.sum()
    return p / s if s > 0 else p


def shadow_snapshots_estimate(psi: np.ndarray, n: int, M: int,
                                 rng: np.random.Generator,
                                 want_features: list[tuple[str, ...]]
                                ) -> np.ndarray:
    """Estimate Pauli expectations from M Pauli-shadow snapshots of |psi>
    using the Huang-Kueng-Preskill (2020) single-qubit-Clifford protocol.

    FAST VERSION: shots are grouped by basis pattern.  Cost is
    O(3^n * 2^n * n + M * n) instead of O(M * 2^n * n) -- ~80x speedup
    for n=4, M=7168.
    """
    PAULI_CODE = {"X": 0, "Y": 1, "Z": 2}

    # Sample M basis patterns at once.
    bases_M = rng.integers(0, 3, size=(M, n), dtype=np.int8)   # (M, n)
    # Pack each pattern into a single integer key in [0, 3^n).
    keys = np.zeros(M, dtype=np.int64)
    for q_ in range(n):
        keys = keys * 3 + bases_M[:, q_]
    # Unique patterns + counts; sort by key for grouped processing.
    order = np.argsort(keys, kind="stable")
    keys_sorted = keys[order]
    bases_sorted = bases_M[order]
    # Find group boundaries.
    boundaries = np.flatnonzero(np.diff(keys_sorted)) + 1
    starts = np.concatenate([[0], boundaries])
    ends   = np.concatenate([boundaries, [M]])

    # We'll fill outcomes (M, n) in the SORTED order, then unsort.
    outcomes_sorted = np.zeros((M, n), dtype=np.int8)
    dim = 2 ** n
    bit_shifts = (n - 1 - np.arange(n)).astype(np.int64)
    for gi in range(len(starts)):
        s_, e_ = starts[gi], ends[gi]
        pattern = tuple(int(b) for b in bases_sorted[s_])    # all same in group
        p = _rotated_probabilities(psi, n, pattern)
        # Sample (e_ - s_) outcomes from this distribution via multinomial:
        # represent as a count vector over the 2^n outcomes, then expand to
        # a list of sample indices (faster than rng.choice per shot).
        counts = rng.multinomial(e_ - s_, p)
        # Build a flat array of sample integer indices respecting counts.
        sample_ints = np.repeat(np.arange(dim, dtype=np.int64), counts)
        rng.shuffle(sample_ints)            # randomize within the group
        # Unpack to bits, MSB-first.
        bits = ((sample_ints[:, None] >> bit_shifts) & 1).astype(np.int8)
        outcomes_sorted[s_:e_, :] = bits

    # Unsort to recover original shot order
    inv_order = np.empty_like(order); inv_order[order] = np.arange(M)
    outcomes = outcomes_sorted[inv_order]

    # +/-1 eigenvalues
    eig = (1 - 2 * outcomes).astype(np.float64)               # (M, n)

    out = np.zeros(len(want_features))
    for fi, feat in enumerate(want_features):
        pairs = [(feat[i], feat[i + 1]) for i in range(0, len(feat), 2)]
        kbody = len(pairs)
        match = np.ones(M, dtype=bool)
        prod_eig = np.ones(M, dtype=np.float64)
        for (lbl, site) in pairs:
            match &= (bases_M[:, site] == PAULI_CODE[lbl])
            prod_eig *= eig[:, site]
        contribs = np.where(match, (3.0 ** kbody) * prod_eig, 0.0)
        out[fi] = contribs.mean()
    return out


def make_shadow_extractor(n_in: int, shots_per_qubit_total: int,
                            q_reservoir: int,
                            rng: np.random.Generator,
                            include_2body: bool = True,
                            mode: str = "noise_model"):
    """Build a feature extractor estimating local Paulis of |psi_in> from
    M = shots_per_qubit_total * q_reservoir Pauli-shadow shots.

    mode='snapshots' : true per-shot simulation (exact, slow, O(M * 2^n_in * n_in)
                       per timestep; only tractable for n_in <= ~6).
    mode='noise_model': analytical -- compute exact <P> and add iid Gaussian
                       noise with the Pauli-shadow per-feature variance
                       Var[<P>_est] = (3^|P| - <P>^2) / M
                       (Huang-Kueng-Preskill 2020, single-qubit Clifford
                       protocol).  Matches per-feature variance to first
                       order; cross-feature covariance is small for
                       most Pauli pairs.  ~100x faster at n_in >= 8.
    """
    M = shots_per_qubit_total * q_reservoir
    want_specs = []        # (pauli_label, sites_tuple)
    want_ops = []           # the corresponding Pauli operator on n_in qubits
    for i in range(n_in):
        for plabel in ("Z", "X", "Y"):
            want_specs.append((plabel, (i,)))
            want_ops.append(single_site(plabel, i, n_in))
    if include_2body:
        for i in range(n_in):
            for j in range(i + 1, n_in):
                for plabel in ("Z", "X", "Y"):
                    want_specs.append((plabel, (i, j)))
                    want_ops.append(two_site(plabel, i, plabel, j, n_in))
    want_weights = np.array([len(s[1]) for s in want_specs])      # |P|
    var_factors = (3.0 ** want_weights) / M                          # 3^|P| / M

    if mode == "snapshots":
        # Legacy slow path (kept for sanity-check on small n_in).
        want_tuples = []
        for (plabel, sites) in want_specs:
            t = []
            for s in sites:
                t.extend([plabel, s])
            want_tuples.append(tuple(t))

        def step(psi_in):
            return shadow_snapshots_estimate(psi_in, n_in, M, rng, want_tuples)

        return step, len(want_specs)

    if mode != "noise_model":
        raise ValueError(f"Unknown shadow mode: {mode}")

    def step(psi_in: np.ndarray) -> np.ndarray:
        # Exact Pauli expectations
        exact = np.empty(len(want_ops))
        for k, O in enumerate(want_ops):
            exact[k] = float(np.real(psi_in.conj() @ (O @ psi_in)))
        # Per-feature variance bound (use 3^|P|/M; the -<P>^2 term only
        # tightens it, so this is slightly conservative for shadows).
        sigma = np.sqrt(np.maximum(var_factors - exact ** 2 / M, var_factors / 2))
        # Actually: keep Var = 3^|P|/M (true upper-bound estimator variance),
        # which is the worst-case classical-shadow guarantee.
        sigma = np.sqrt(var_factors)
        noise = rng.standard_normal(len(want_ops)) * sigma
        return exact + noise

    return step, len(want_specs)


def make_cheating_classical_extractor(n_in: int, include_2body: bool = True):
    """Exact local Pauli features on |psi_in>, no shot noise."""
    want = []
    ops = []
    for i in range(n_in):
        for p in ("Z", "X", "Y"):
            want.append((p, i))
            ops.append(single_site(p, i, n_in))
    if include_2body:
        for i in range(n_in):
            for j in range(i + 1, n_in):
                for p in ("Z", "X", "Y"):
                    want.append((p, i, p, j))
                    ops.append(two_site(p, i, p, j, n_in))

    def step(psi_in: np.ndarray) -> np.ndarray:
        out = np.empty(len(ops))
        for k, O in enumerate(ops):
            out[k] = float(np.real(psi_in.conj() @ (O @ psi_in)))
        return out

    return step, len(want)


